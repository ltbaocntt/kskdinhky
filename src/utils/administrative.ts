// Flat list for easy search
export interface FlatDivisionSearch {
  provinceName: string;
  provinceCode: string;
  communeName: string;
  communeCode: string;
}

export const getFlatDivisionsList = (): FlatDivisionSearch[] => {
  const result: FlatDivisionSearch[] = [];
  VIETNAM_ADMINISTRATIVE_DIVISIONS.forEach(prov => {
    prov.communes.forEach(comm => {
      result.push({
        provinceName: prov.name,
        provinceCode: prov.code,
        communeName: comm.name,
        communeCode: comm.code
      });
    });
  });
  return result;
};
